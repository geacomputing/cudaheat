"""Extend an hourly SST NetCDF forward for CUDAHeat benchmarks.

The original SST record is preserved unchanged.

Synthetic data are generated by cyclically repeating the original
record and applying a configurable linear warming trend.

The original (time, latitude, longitude) structure is preserved.

This utility generates synthetic data for computational benchmarking
only. It is NOT a scientific SST projection.
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

import numpy as np
from netCDF4 import Dataset, date2num, num2date


# ============================================================
# USER CONFIGURATION
# ============================================================

INPUT_PATH = Path(
    "/home/user/Documents/PhD.cy/lazy_loading/cudaHeat/sst_8_years.nc"
)

# Save output in the same directory as this Python script.
OUTPUT_PATH = Path(__file__).resolve().parent / "sst_40_years.nc"

VARIABLE = "analysed_sst"

# Inclusive last timestamp of the synthetic dataset.
END_DATE = "2058-12-31T23:00:00"

# Linear warming: 1 degree Celsius every 5 years.
WARMING_PER_5_YEARS = 1.0

# Number of hourly timesteps processed per I/O block.
BLOCK_HOURS = 168

# Prevent accidental overwriting.
OVERWRITE = False


# ============================================================
# NETCDF EXTENSION
# ============================================================

def extend_sst(
    source: str | Path,
    destination: str | Path,
    *,
    end_date: str,
    variable: str = "analysed_sst",
    warming_per_5_years: float = 1.0,
    block_hours: int = 168,
    overwrite: bool = False,
) -> dict:
    """Extend an existing hourly SST NetCDF with synthetic future data."""

    source = Path(source)
    destination = Path(destination)

    if source.resolve() == destination.resolve():
        raise ValueError("Input and output must differ.")

    if destination.exists() and not overwrite:
        raise FileExistsError(
            f"Output already exists: {destination}"
        )

    if block_hours < 1:
        raise ValueError("BLOCK_HOURS must be positive.")

    destination.parent.mkdir(parents=True, exist_ok=True)

    with Dataset(source, "r") as src:

        if variable not in src.variables:
            raise KeyError(f"Variable {variable!r} not found.")

        sst = src.variables[variable]

        if sst.dimensions[0] != "time" or sst.ndim != 3:
            raise ValueError(
                "Expected SST dimensions: "
                "(time, latitude, longitude)"
            )

        time = src.variables["time"]

        if len(time) < 2:
            raise ValueError("At least two timestamps are required.")

        calendar = getattr(time, "calendar", "standard")
        units = time.units

        dates = num2date(
            time[:],
            units=units,
            calendar=calendar,
        )

        delta = dates[1] - dates[0]

        if delta.total_seconds() <= 0:
            raise ValueError("Time must be strictly increasing.")

        if any(
            dates[i + 1] - dates[i] != delta
            for i in range(len(dates) - 1)
        ):
            raise ValueError(
                "Input dataset must have a regular time axis."
            )

        target = datetime.fromisoformat(end_date)

        end_num = float(
            date2num(target, units, calendar=calendar)
        )

        last_num = float(time[-1])
        step_num = float(time[1] - time[0])

        if end_num < last_num:
            raise ValueError(
                "END_DATE must be later than the original record."
            )

        extra_float = (end_num - last_num) / step_num
        extra = int(round(extra_float))

        if not np.isclose(
            extra_float,
            extra,
            rtol=0,
            atol=1e-5,
        ):
            raise ValueError(
                "END_DATE must align with the hourly cadence."
            )

        original_n = len(time)

        print(f"Original timesteps : {original_n:,}")
        print(f"Synthetic timesteps: {extra:,}")
        print(f"Total timesteps    : {original_n + extra:,}")
        print(f"Output             : {destination}")

        # ====================================================
        # CREATE OUTPUT NETCDF
        # ====================================================

        with Dataset(
            destination,
            "w",
            format="NETCDF4",
        ) as dst:

            # Preserve original dimensions.
            for name, dim in src.dimensions.items():
                dst.createDimension(
                    name,
                    None if name == "time" else len(dim),
                )

            # Preserve global attributes.
            dst.setncatts({
                name: src.getncattr(name)
                for name in src.ncattrs()
            })

            dst.setncattr(
                "cudaheat_synthetic_benchmark",
                "Forward cyclic SST repetition with linear warming; "
                "NOT a scientific projection.",
            )

            dst.setncattr(
                "cudaheat_synthetic_warming_C_per_5_years",
                float(warming_per_5_years),
            )

            dst.setncattr(
                "cudaheat_synthetic_original_timesteps",
                original_n,
            )

            dst.setncattr(
                "cudaheat_synthetic_source",
                source.name,
            )

            # =================================================
            # CREATE VARIABLES
            # =================================================

            for name, v in src.variables.items():

                if name == variable:

                    # Store decoded SST as float32.
                    # This avoids packed-int16 overflow when
                    # applying the synthetic warming trend.

                    out = dst.createVariable(
                        name,
                        "f4",
                        v.dimensions,
                        fill_value=np.float32(np.nan),
                    )

                    attrs = {
                        k: v.getncattr(k)
                        for k in v.ncattrs()
                        if k not in (
                            "_FillValue",
                            "scale_factor",
                            "add_offset",
                            "missing_value",
                        )
                    }

                    out.setncatts(attrs)

                    out.setncattr(
                        "comment",
                        "Synthetic SST extension for "
                        "computational benchmarking only.",
                    )

                elif name == "time":

                    out = dst.createVariable(
                        name,
                        "f8",
                        v.dimensions,
                    )

                    out.setncatts({
                        k: v.getncattr(k)
                        for k in v.ncattrs()
                        if k != "_FillValue"
                    })

                else:

                    fill = (
                        v.getncattr("_FillValue")
                        if "_FillValue" in v.ncattrs()
                        else None
                    )

                    out = dst.createVariable(
                        name,
                        v.dtype,
                        v.dimensions,
                        fill_value=fill,
                    )

                    out.setncatts({
                        k: v.getncattr(k)
                        for k in v.ncattrs()
                        if k != "_FillValue"
                    })

                    # Static coordinates are copied unchanged.
                    if "time" not in v.dimensions:
                        out[:] = v[:]

            # =================================================
            # COPY ORIGINAL DATA
            # =================================================

            print("Copying original SST record...")

            for start in range(0, original_n, block_hours):

                stop = min(
                    start + block_hours,
                    original_n,
                )

                for name, v in src.variables.items():

                    if "time" not in v.dimensions:
                        continue

                    idx = v.dimensions.index("time")

                    selector = [slice(None)] * v.ndim
                    selector[idx] = slice(start, stop)

                    dst.variables[name][tuple(selector)] = (
                        v[tuple(selector)]
                    )

            # =================================================
            # GENERATE SYNTHETIC FUTURE DATA
            # =================================================

            print("Generating synthetic future SST...")

            for offset in range(0, extra, block_hours):

                count = min(
                    block_hours,
                    extra - offset,
                )

                output_indices = (
                    original_n
                    + offset
                    + np.arange(count)
                )

                # Repeat the original record cyclically.
                source_indices = (
                    offset + np.arange(count)
                ) % original_n

                # Generate future timestamps.
                dst.variables["time"][output_indices] = (
                    last_num
                    + (offset + 1 + np.arange(count))
                    * step_num
                )

                for name, v in src.variables.items():

                    if "time" not in v.dimensions:
                        continue

                    if name == "time":
                        continue

                    idx = v.dimensions.index("time")

                    if name == variable:

                        # Decode original SST values.
                        values = np.ma.asarray(
                            v[source_indices, ...],
                            dtype=np.float32,
                        )

                        # Years elapsed after original record.
                        years = (
                            (offset + 1 + np.arange(count))
                            * delta.total_seconds()
                            / (365.2425 * 86400)
                        )

                        # Linear warming trend.
                        trend = (
                            warming_per_5_years / 5.0
                        ) * years

                        trend = trend.astype(
                            np.float32
                        ).reshape((-1, 1, 1))

                        # Preserve missing values.
                        values = values + trend

                        dst.variables[name][
                            output_indices, ...
                        ] = values.filled(np.nan)

                    else:

                        # Repeat time-dependent auxiliary variables.
                        for j, source_i in enumerate(source_indices):

                            src_sel = [slice(None)] * v.ndim
                            dst_sel = [slice(None)] * v.ndim

                            src_sel[idx] = int(source_i)
                            dst_sel[idx] = int(output_indices[j])

                            dst.variables[name][
                                tuple(dst_sel)
                            ] = v[tuple(src_sel)]

                completed = offset + count

                if completed % (block_hours * 100) == 0:
                    print(
                        f"Synthetic progress: "
                        f"{completed:,}/{extra:,} hours"
                    )

    return {
        "input": str(source),
        "output": str(destination),
        "original_timesteps": original_n,
        "synthetic_timesteps": extra,
        "total_timesteps": original_n + extra,
        "warming_C_per_5_years": warming_per_5_years,
        "last_timestamp": end_date,
    }


# ============================================================
# MAIN
# ============================================================

def main():

    report = extend_sst(
        INPUT_PATH,
        OUTPUT_PATH,
        end_date=END_DATE,
        variable=VARIABLE,
        warming_per_5_years=WARMING_PER_5_YEARS,
        block_hours=BLOCK_HOURS,
        overwrite=OVERWRITE,
    )

    print("\n" + "=" * 60)
    print("SYNTHETIC NETCDF GENERATION COMPLETED")
    print("=" * 60)

    for key, value in report.items():
        print(f"{key}: {value}")


if __name__ == "__main__":
    main()